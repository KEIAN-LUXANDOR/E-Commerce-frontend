export interface DeliveryAddress {
  id: string;
  fullName: string;
  phone: string;
  line1: string;
  line2: string | null;
  landmark: string | null;
  city: string;
  state: string;
  pincode: string;
  defaultAddress: boolean;
}

export interface DeliveryAddressRequest {
  fullName: string;
  phone: string;
  line1: string;
  line2?: string;
  landmark?: string;
  city: string;
  state: string;
  pincode: string;
  /** true makes it the default address */
  makeDefault?: boolean;
}
